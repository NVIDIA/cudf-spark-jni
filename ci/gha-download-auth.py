"""Filter download credentials before publishing GHA console or diagnostic files."""

import argparse
import base64
import netrc
from pathlib import Path
import shutil
import sys


# Keep full reports, but never publish the raw workspace after authenticated downloads.
EVIDENCE = (
    "target/gha-*.log", "target/gha-*.txt", "target/surefire-reports/*",
    "target/**/Testing/Temporary/*.log", "target/**/CMakeFiles/CMakeConfigureLog.yaml",
    "target/**/CMakeFiles/CMakeError.log", "target/**/CMakeFiles/CMakeOutput.log",
    "target/**/hs_err_pid*.log", "hs_err_pid*.log", "monte.rmm.log", "monte.state.log",
)


def credentials(path):
    # This is the private, single-host file generated by gha-premerge.sh, not HOME.
    values = netrc.netrc(path).authenticators("github.com")
    if values is None:
        return ()
    username, _, password = values
    return (base64.b64encode(f"{username}:{password}".encode()), password.encode())


def redact(source, destination, secrets, flush=False):
    for line in source:
        # Literal replacement handles inline/folded Basic headers without removing
        # surrounding XML/YAML markup or swallowing the useful download error.
        for secret in secrets:
            if secret:
                line = line.replace(secret, b"****")
        destination.write(line)
        if flush:
            destination.flush()


def stage(workspace, destination, secrets):
    workspace = Path(workspace).resolve()
    destination = Path(destination)
    # Fail closed on stale/partially staged evidence rather than mixing old logs.
    destination.mkdir(mode=0o700)
    try:
        files = {path for pattern in EVIDENCE for path in workspace.glob(pattern)}
        for path in sorted(files):
            relative = path.relative_to(workspace)
            # Do not follow a workload-created symlink outside the evidence set.
            if any(parent.is_symlink() for parent in (path, *path.parents)
                   if parent != workspace and workspace in parent.parents):
                raise ValueError("Symlink in diagnostic input")
            if not path.is_file():
                continue
            target = destination / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            with path.open("rb") as source, target.open("wb") as output:
                redact(source, output, secrets)
    except Exception:
        shutil.rmtree(destination)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("netrc_file")
    parser.add_argument("--stage", metavar="DIRECTORY")
    args = parser.parse_args()
    try:
        secrets = credentials(args.netrc_file)
        if args.stage:
            stage(Path.cwd(), args.stage, secrets)
        else:
            redact(sys.stdin.buffer, sys.stdout.buffer, secrets, flush=True)
    except Exception:
        # Parser exceptions can contain credential-file contents. Never echo them.
        print("Credential filtering failed; raw diagnostics will not be published.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
